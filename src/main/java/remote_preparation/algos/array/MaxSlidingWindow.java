package remote_preparation.algos.array;

import java.util.ArrayDeque;
import java.util.Deque;

public class MaxSlidingWindow {

    /**
     * МОНОТОННАЯ ДЕКА: хранит ИНДЕКСЫ (не значения!), причём значения
     * по этим индексам всегда идут СТРОГО ПО УБЫВАНИЮ от головы к хвосту.
     * Голова деки — это всегда индекс максимума текущего окна.
     *
     * ПОЧЕМУ ХРАНЯТСЯ ИНДЕКСЫ, А НЕ ЗНАЧЕНИЯ:
     * чтобы вовремя понять, что элемент "устарел" — вышел из окна
     * по левой границе — нужно знать его ПОЗИЦИЮ, а не только величину.
     * Одинаковые значения на разных позициях иначе неразличимы.
     *
     * ДВА ПРАВИЛА ПОДДЕРЖАНИЯ ИНВАРИАНТА на каждом шаге i:
     *
     * 1) Перед добавлением nums[i] выкидываем с ХВОСТА все индексы,
     *    чьи значения <= nums[i]. Они больше НИКОГДА не станут
     *    максимумом ни в одном будущем окне: nums[i] новее (значит,
     *    будет в окне дольше) и не меньше — эти элементы бесполезны
     *    раз и навсегда, не только сейчас. Именно это отбрасывание
     *    и делает деку монотонной, а амортизированную сложность — O(1)
     *    на элемент (см. пояснение по сложности ниже).
     *
     * 2) Перед чтением максимума проверяем ГОЛОВУ: если её индекс
     *    выпал из текущего окна (dq.peekFirst() <= i - k), выкидываем
     *    её С ГОЛОВЫ. Это единственная причина, по которой элемент
     *    может покинуть деку С ГОЛОВЫ, а не с хвоста, — устаревание
     *    по позиции, а не по величине.
     *
     * Ответ для окна, заканчивающегося в позиции i, — значение
     * по индексу на ГОЛОВЕ деки, но фиксируется только когда i >= k-1
     * (то есть когда первое полноценное окно размера k уже сформировано).
     *
     * ============================================================
     * ПОЧЕМУ ЭТО O(n), А НЕ ПРОСТО "ЭВРИСТИКА"
     * ============================================================
     * Каждый индекс добавляется в деку РОВНО ОДИН РАЗ (на шаге i)
     * и может быть удалён ИЗ НЕЁ РОВНО ОДИН РАЗ (либо с хвоста
     * по правилу 1, либо с головы по правилу 2, но не оба варианта
     * сразу для одного и того же индекса). Суммарное число операций
     * добавления и удаления за весь проход — не больше 2n, значит
     * АМОРТИЗИРОВАННАЯ стоимость на один шаг i — O(1), несмотря
     * на то что отдельный шаг МОЖЕТ выкинуть сразу несколько элементов
     * с хвоста за один раз (тот же "банковский метод", что и в задаче
     * про очередь на двух стеках: дорогие шаги оплачиваются заранее
     * накопленными дешёвыми).
     *
     * ============================================================
     * ПОЧЕМУ НАИВНОЕ O(n*k) ХУЖЕ — И НЕ ПРОСТО КОНСТАНТОЙ
     * ============================================================
     * Наивный подход: для каждой из (n-k+1) стартовых позиций окна
     * заново пройтись по всем k элементам и найти максимум — O(n*k).
     *
     * Дело не в лишней константе, а в том, что наивный подход ПОВТОРНО
     * пересчитывает почти ОДНУ И ТУ ЖЕ РАБОТУ на каждом шаге: окно
     * [i, i+k) и окно [i+1, i+k+1) пересекаются в (k-1) элементах
     * из k, но наивный алгоритм каждый раз ищет максимум среди ВСЕХ k
     * заново, включая уже просмотренные элементы. Дека это устраняет
     * структурно: КАЖДЫЙ элемент массива обрабатывается (добавляется
     * и, возможно, позже удаляется) НЕ БОЛЕЕ ДВУХ РАЗ за весь проход,
     * а не k раз для каждого окна, в которое он потенциально входит.
     *
     * При больших k (например, k близко к n, а n порядка 10^6)
     * разница между O(n) и O(n*k) — это разница между долями секунды
     * и часами работы, а не "чуть медленнее". При k=n/2 наивный подход
     * уже квадратичен по n.
     */
    static int[] maxSlidingWindow(int[] nums, int k) {
        if (nums.length == 0 || k <= 0) {
            return new int[0];
        }

        Deque<Integer> deque = new ArrayDeque<>(); // индексы, значения по убыванию
        int[] result = new int[nums.length - k + 1];

        for (int i = 0; i < nums.length; i++) {
            // Правило 1: выкидываем с хвоста все индексы с меньшим/равным значением —
            // они больше никогда не станут максимумом
            while (!deque.isEmpty() && nums[deque.peekLast()] <= nums[i]) {
                deque.pollLast();
            }
            deque.addLast(i);

            // Правило 2: выкидываем с головы индекс, вышедший за левую границу окна
            if (deque.peekFirst() <= i - k) {
                deque.pollFirst();
            }

            // Окно размера k впервые сформировано на позиции i == k-1
            if (i >= k - 1) {
                result[i - k + 1] = nums[deque.peekFirst()];
            }
        }

        return result;
    }

    public static void main(String[] args) {
        check(maxSlidingWindow(new int[]{1, 3, -1, -3, 5, 3, 6, 7}, 3),
                new int[]{3, 3, 5, 5, 6, 7}, "пример из условия");
        check(maxSlidingWindow(new int[]{1}, 1), new int[]{1}, "один элемент, k=1");
        check(maxSlidingWindow(new int[]{9, 8, 7, 6}, 2), new int[]{9, 8, 7}, "убывающий массив");
        check(maxSlidingWindow(new int[]{1, 2, 3, 4}, 2), new int[]{2, 3, 4}, "возрастающий массив");
        check(maxSlidingWindow(new int[]{5, 5, 5, 5}, 2), new int[]{5, 5, 5}, "все элементы одинаковые");
        check(maxSlidingWindow(new int[]{4, 3}, 1), new int[]{4, 3}, "k=1: результат равен исходному массиву");
        check(maxSlidingWindow(new int[]{1, 3, 1, 2, 0, 5}, 3), new int[]{3, 3, 2, 5}, "смешанный порядок");
        check(maxSlidingWindow(new int[]{}, 3), new int[]{}, "пустой массив");

        System.out.println("Все проверки пройдены");
    }

    private static void check(int[] actual, int[] expected, String label) {
        if (!java.util.Arrays.equals(actual, expected)) {
            throw new AssertionError(label + ": ожидали " + java.util.Arrays.toString(expected)
                    + ", получили " + java.util.Arrays.toString(actual));
        }
        System.out.println("OK  " + label);
    }
}
