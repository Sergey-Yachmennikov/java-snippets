package remote_preparation.marketplace;

import java.util.HashSet;
import java.util.Set;
import java.util.concurrent.ThreadLocalRandom;

public class UniqRandn {

    /**
     * ============================================================
     * ПОЧЕМУ ЭТО ЗАДАЧА НА ПЕРЕСТАНОВКУ, А НЕ НА "СЛУЧАЙНУЮ ВЫБОРКУ"
     * ============================================================
     * Диапазон значений — РОВНО [0, n-1], и требуется РОВНО n уникальных
     * чисел. То есть результат обязан содержать КАЖДОЕ число из диапазона
     * ровно один раз — это не подмножество диапазона, а его ПОЛНАЯ
     * ПЕРЕСТАНОВКА (permutation) в случайном порядке. Задача сводится
     * к "перемешать [0, 1, ..., n-1]", а не к "выбрать n случайных
     * непересекающихся чисел откуда-то".
     *
     * Эта деталь исключает наивный подход "генерировать случайное число
     * в [0, n-1], проверять на повтор через Set, при повторе — повторить
     * попытку" (rejection sampling). Такой подход РАБОТАЛ БЫ корректно
     * по результату, но его СЛОЖНОСТЬ КАТАСТРОФИЧЕСКИ УХУДШАЕТСЯ именно
     * потому, что диапазон РАВЕН количеству нужных чисел, а не больше
     * него:
     *
     *   - когда уже набрано n-1 из n чисел, диапазон [0, n-1] содержит
     *     ТОЛЬКО ОДНО ещё не занятое число — вероятность попасть в него
     *     одним броском равна 1/n;
     *   - ОЖИДАЕМОЕ число попыток, чтобы поймать это последнее число,
     *     равно n (геометрическое распределение с p=1/n);
     *   - это классическая "задача о купонах" (coupon collector problem):
     *     ожидаемое ОБЩЕЕ число попыток для сбора всех n уникальных
     *     значений методом проб — O(n log n), а не O(n). При этом
     *     ХУДШИЙ СЛУЧАЙ теоретически НЕОГРАНИЧЕН (можно как угодно
     *     долго не попадать в последнее свободное число, хоть и с
     *     исчезающей вероятностью) — то есть у наивного подхода даже
     *     НЕТ гарантированной верхней границы по времени выполнения,
     *     только вероятностная.
     *
     * ============================================================
     * ПРАВИЛЬНЫЙ ИНСТРУМЕНТ: ТАСОВКА ФИШЕРА-ЙЕЙТСА (FISHER-YATES SHUFFLE)
     * ============================================================
     * Вместо "угадывать" числа заново каждый раз, заполняем массив
     * ПОСЛЕДОВАТЕЛЬНО [0, 1, ..., n-1] (никаких повторов по построению,
     * без проверок вообще), а затем ПЕРЕМЕШИВАЕМ его за один проход:
     *
     * Идём с КОНЦА массива к началу. На шаге i выбираем случайный индекс
     * j РАВНОМЕРНО из [0, i] (включая саму позицию i) и меняем местами
     * элементы на позициях i и j. После этого позиция i считается
     * "зафиксированной" и больше не трогается.
     *
     * ПОЧЕМУ ЭТО ДАЁТ РАВНОМЕРНОЕ РАСПределение ПО ВСЕМ n! ПЕРЕСТАНОВКАМ
     * (а не просто "какой-то случайный порядок" — это доказуемо строго):
     * на шаге, где обрабатывается позиция i (от n-1 до 0), у элемента,
     * который в итоге там окажется, было РОВНО i+1 равновероятных
     * кандидатов (весь ещё "живой" префикс [0, i]) — значит вероятность
     * оказаться на позиции i у любого из оставшихся элементов ОДИНАКОВА
     * и равна 1/(i+1). Перемножив эти независимые вероятности по всем
     * позициям, получаем, что КАЖДАЯ из n! перестановок равновероятна.
     * Наивный "неправильный" вариант тасовки (выбор j из ВСЕГО диапазона
     * [0, n-1] на каждом шаге, а не из СУЖАЮЩЕГОСЯ [0, i]) НЕ даёт
     * равномерного распределения — это классическая, часто встречаемая
     * ошибка реализации, известная как "не Fisher-Yates, а похожий,
     * но статистически смещённый алгоритм".
     *
     * Сложность: O(n) времени (один проход, n-1 обменов), O(1)
     * дополнительной памяти (не считая самого результирующего массива,
     * который нужен в любом случае как возвращаемое значение) —
     * никакого Set для проверки уникальности не требуется вообще,
     * уникальность гарантирована ПОСТРОЕНИЕМ (это перестановка
     * УЖЕ уникального набора, а не независимая генерация с проверками).
     */
    static int[] uniqRandn(int n) {
        if (n < 0) {
            throw new IllegalArgumentException("n не может быть отрицательным: " + n);
        }

        int[] result = new int[n];
        for (int i = 0; i < n; i++) {
            result[i] = i;
        }

        ThreadLocalRandom random = ThreadLocalRandom.current();
        for (int i = n - 1; i > 0; i--) {
            // nextInt(i + 1) — равномерно из [0, i] ВКЛЮЧИТЕЛЬНО,
            // а не [0, n-1] — именно СУЖАЮЩИЙСЯ диапазон и есть
            // ключевое условие корректности Fisher-Yates, см. выше
            int j = random.nextInt(i + 1);
            int tmp = result[i];
            result[i] = result[j];
            result[j] = tmp;
        }

        return result;
    }

    public static void main(String[] args) {
        checkPermutation(uniqRandn(10), 10, "n=10: базовый случай из условия");
        checkPermutation(uniqRandn(1), 1, "n=1: единственное число — [0]");
        checkPermutation(uniqRandn(0), 0, "n=0: пустой результат");
        checkPermutation(uniqRandn(2), 2, "n=2: минимальный нетривиальный случай");
        checkPermutation(uniqRandn(1000), 1000, "n=1000: большой диапазон");

        try {
            uniqRandn(-1);
            throw new AssertionError("ожидали исключение при отрицательном n");
        } catch (IllegalArgumentException e) {
            System.out.println("OK  отрицательный n корректно отвергается");
        }

        // Санити-проверка распределения: при n=2 обе перестановки
        // [0,1] и [1,0] должны появляться примерно поровну на многих
        // прогонах — грубая, но полезная проверка отсутствия явного
        // смещения (не строгий статистический тест, а дымовая проверка)
        int trials = 100_000;
        int countFirstIsZero = 0;
        for (int t = 0; t < trials; t++) {
            int[] r = uniqRandn(2);
            if (r[0] == 0) {
                countFirstIsZero++;
            }
        }
        double ratio = (double) countFirstIsZero / trials;
        System.out.printf("Доля перестановок [0,1] из %d прогонов: %.3f (ожидаем ~0.5)%n", trials, ratio);
        if (Math.abs(ratio - 0.5) > 0.02) {
            throw new AssertionError("подозрение на смещённое распределение: " + ratio);
        }
        System.out.println("OK  распределение выглядит равномерным (санити-проверка)");

        System.out.println("Все проверки пройдены");
    }

    /** Проверяет, что result — валидная перестановка [0, n-1]: правильная длина, все значения уникальны и в диапазоне. */
    private static void checkPermutation(int[] result, int n, String label) {
        if (result.length != n) {
            throw new AssertionError(label + ": ожидали длину " + n + ", получили " + result.length);
        }

        Set<Integer> seen = new HashSet<>();
        for (int v : result) {
            if (v < 0 || v >= n) {
                throw new AssertionError(label + ": значение " + v + " вне диапазона [0, " + (n - 1) + "]");
            }
            if (!seen.add(v)) {
                throw new AssertionError(label + ": повторяющееся значение " + v + " в " + java.util.Arrays.toString(result));
            }
        }
        if (seen.size() != n) {
            throw new AssertionError(label + ": ожидали " + n + " уникальных значений, получили " + seen.size());
        }

        System.out.println("OK  " + label + " -> " + java.util.Arrays.toString(result));
    }
}
